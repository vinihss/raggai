func (r renderer) dominio() string {
	var b strings.Builder
	b.WriteString(generatedHeader)
	b.WriteString("\n# Domínio\n\n")
	b.WriteString("Catálogo de agregados. Cada linha aponta para o documento da feature (regra DOC6: catálogo não duplica prosa).\n\n")

	if len(r.features) == 0 && r.service.Mode == "minimal" {
		b.WriteString("Nenhuma feature de negócio ainda. Gere uma com `new-feature.sh`.\n")
		return b.String()
	}

	b.WriteString("| Agregado | Pacote | Campos | Invariantes |\n")
	b.WriteString("| --- | --- | --- | --- |\n")
	if r.service.Mode != "minimal" {
		b.WriteString("| `Ping` (exemplo) | `internal/domain/ping` | `id`, `message`, `created_at` | `message` obrigatório; `created_at` vem do Clock |\n")
	}
	for _, f := range r.features {
		fmt.Fprintf(&b, "| [%s](features/%s.md) | `internal/domain/%s` | %d | %s |\n",
			f.Feature.Aggregate, f.Feature.Name, f.Feature.Name, len(f.Fields), invariantSummary(f))
	}

	b.WriteString("\nRegras do guia aplicadas a todo agregado:\n\n")
	b.WriteString("- Campos privados; a única porta de entrada é `New(...)`.\n")
	b.WriteString("- `Rehydrate(Params)` existe nos agregados gerados para o adapter de saída reconstruir dados já validados.\n")
	b.WriteString("- Erros de invariante são `ValidationError{Field, Message}`, sem importar HTTP.\n")
	b.WriteString("- `Ping` é o exemplo do scaffold; pode ser removido quando não servir mais de referência.\n")
	return b.String()
}

func (r renderer) api() string {
	var b strings.Builder
	b.WriteString(generatedHeader)
	b.WriteString("\n# API\n\n")
	b.WriteString("Rotas registradas no mux versionado. O prefixo `/api/v1` é aplicado uma única vez em `http.Mount`.\n\n")

	if len(r.features) == 0 && r.service.Mode == "minimal" {
		b.WriteString("Nenhuma rota de negócio além de `/healthz` e `/readyz`.\n")
	} else {
		b.WriteString("| Método | Rota | Sucesso | Caso de uso | Feature |\n")
		b.WriteString("| --- | --- | --- | --- | --- |\n")
		if r.service.Mode != "minimal" {
			b.WriteString("| POST | `/ping` | 201 | Create | exemplo do scaffold |\n")
		}
		for _, f := range r.features {
			for _, uc := range f.UseCases {
				if uc.HTTP == nil {
					continue
				}
				fmt.Fprintf(&b, "| %s | `%s` | %d | %s | [%s](features/%s.md) |\n",
					uc.HTTP.Method, uc.HTTP.Path, uc.HTTP.Status, uc.Name, f.Feature.Name, f.Feature.Name)
			}
		}
		b.WriteString("\nRotas da tabela são relativas ao prefixo `/api/v1`.\n")
	}

	b.WriteString("\n## Fora do prefixo\n\n")
	b.WriteString("| Método | Rota | Efeito |\n| --- | --- | --- |\n")
	b.WriteString("| GET | `/healthz` | Liveness: processo vivo. |\n")
	b.WriteString("| GET | `/readyz` | Readiness: dependências prontas. |\n")

	b.WriteString("\n## Formato de erro\n\n")
	b.WriteString("Todo erro usa o mesmo envelope:\n\n")
	b.WriteString("```json\n{\"code\": \"validation_error\", \"message\": \"amount_cents must be >= 1\"}\n```\n\n")
	b.WriteString("| Situação | HTTP | `code` |\n| --- | --- | --- |\n")
	b.WriteString("| Corpo inválido | 400 | `validation_error` |\n")
	b.WriteString("| Invariante violada | 422 | `validation_error` |\n")
	b.WriteString("| Recurso ausente | 404 | `not_found` |\n")
	b.WriteString("| Conflito de unicidade | 409 | `conflict` |\n")
	b.WriteString("| Falha inesperada | 500 | `internal` |\n\n")
	b.WriteString("O mapeamento vive em um único arquivo, `internal/adapters/inbound/http/errors.go`.\n")
	return b.String()
}

func (r renderer) dados() string {
	var b strings.Builder
	b.WriteString(generatedHeader)
	b.WriteString("\n# Dados\n\n")

	withPostgres := false
	for _, f := range r.features {
		if f.Adapters.Postgres {
			withPostgres = true
		}
	}

	if !withPostgres && r.service.Mode != "full" {
		b.WriteString("Este serviço está no modo `" + r.service.Mode + "`: não há banco de dados. O adapter em memória é usado nos testes e no `make run`.\n")
		return b.String()
	}

	b.WriteString("Migrations são forward-only: uma migration aplicada nunca é reescrita (regra S7/O7).\n\n")
	b.WriteString("| Tabela | Migration | Feature | Adapters |\n| --- | --- | --- | --- |\n")
	if r.service.Mode == "full" {
		b.WriteString("| `pings` | `0001_create_pings.sql` | exemplo do scaffold | postgres |\n")
	}
	for _, f := range r.features {
		adapters := make([]string, 0, 2)
		if f.Adapters.Memory {
			adapters = append(adapters, "memory")
		}
		if f.Adapters.Postgres {
			adapters = append(adapters, "postgres")
		}
		migration := r.migrations[f.Feature.Name]
		if migration == "" && f.Adapters.Postgres {
			migration = "(pendente)"
		}
		if migration == "" {
			migration = "—"
		}
		fmt.Fprintf(&b, "| `%s` | `%s` | [%s](features/%s.md) | %s |\n",
			f.Feature.Table, migration, f.Feature.Name, f.Feature.Name, strings.Join(adapters, ", "))
	}

	b.WriteString("\n## Transações\n\n")
	b.WriteString("O caso de uso nunca abre transação. Quando precisar de atomicidade entre repositórios, receba a porta `tx.UnitOfWork` e envolva o trabalho:\n\n")
	b.WriteString("```go\nerr := uow.WithinTransaction(ctx, func(ctx context.Context) error {\n    // repositórios participam da transação via context\n    return nil\n})\n```\n\n")
	b.WriteString("O adapter Postgres guarda o `pgx.Tx` no context e o repositório escolhe entre pool e transação com `querier(ctx, pool)`.\n")
	return b.String()
}

