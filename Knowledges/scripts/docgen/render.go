func (r renderer) feature(f FeatureSpec) string {
	var b strings.Builder
	b.WriteString(generatedHeader)
	fmt.Fprintf(&b, "\n# %s\n\n", f.Feature.Aggregate)
	if f.Feature.Description != "" {
		fmt.Fprintf(&b, "%s\n\n", f.Feature.Description)
	}
	fmt.Fprintf(&b, "Pacote `internal/domain/%s` · tabela `%s` · rota base `%s`.\n\n", f.Feature.Name, f.Feature.Table, f.Feature.Route)

	b.WriteString("## Campos\n\n")
	b.WriteString("| Campo | Tipo | Obrigatório | Notas |\n| --- | --- | --- | --- |\n")
	for _, field := range f.Fields {
		notes := make([]string, 0, 4)
		if field.PK {
			notes = append(notes, "PK")
		}
		if field.Nullable {
			notes = append(notes, "nullable")
		}
		if field.Unique {
			notes = append(notes, "unique")
		}
		if field.Name == "created_at" || field.Name == "updated_at" {
			notes = append(notes, "preenchido pelo Clock")
		}
		if field.MaxLen != nil {
			notes = append(notes, fmt.Sprintf("máx. %d caracteres", *field.MaxLen))
		}
		if field.Min != nil {
			notes = append(notes, fmt.Sprintf("mín. %v", *field.Min))
		}
		if field.Max != nil {
			notes = append(notes, fmt.Sprintf("máx. %v", *field.Max))
		}
		if len(field.Enum) > 0 {
			notes = append(notes, "enum: `"+strings.Join(field.Enum, "`, `")+"`")
		}
		if field.Default != nil {
			notes = append(notes, fmt.Sprintf("default `%v`", field.Default))
		}
		required := "não"
		if field.Required {
			required = "sim"
		}
		note := "—"
		if len(notes) > 0 {
			note = strings.Join(notes, ", ")
		}
		fmt.Fprintf(&b, "| `%s` | `%s` | %s | %s |\n", field.Name, field.Type, required, note)
	}

	b.WriteString("\n## Casos de uso\n\n")
	b.WriteString("| Caso de uso | Método | Rota | Sucesso |\n| --- | --- | --- | --- |\n")
	for _, uc := range f.UseCases {
		if uc.HTTP == nil {
			continue
		}
		fmt.Fprintf(&b, "| %s | %s | `%s` | %d |\n", uc.Name, uc.HTTP.Method, uc.HTTP.Path, uc.HTTP.Status)
	}

	b.WriteString("\n## Arquivos\n\n")
	b.WriteString("| Camada | Arquivo |\n| --- | --- |\n")
	fmt.Fprintf(&b, "| domain | [`internal/domain/%s/%s.go`](../../internal/domain/%s/%s.go) |\n", f.Feature.Name, f.Feature.Name, f.Feature.Name, f.Feature.Name)
	fmt.Fprintf(&b, "| ports | [`internal/ports/repositories/%s.go`](../../internal/ports/repositories/%s.go) |\n", f.Feature.Name, f.Feature.Name)
	fmt.Fprintf(&b, "| application | [`internal/application/%s/service.go`](../../internal/application/%s/service.go) |\n", f.Feature.Name, f.Feature.Name)
	fmt.Fprintf(&b, "| http | [`internal/adapters/inbound/http/%s.go`](../../internal/adapters/inbound/http/%s.go) |\n", f.Feature.Name, f.Feature.Name)
	fmt.Fprintf(&b, "| dto | [`internal/adapters/inbound/http/dto/%s.go`](../../internal/adapters/inbound/http/dto/%s.go) |\n", f.Feature.Name, f.Feature.Name)
	if f.Adapters.Memory {
		fmt.Fprintf(&b, "| memory | [`internal/adapters/outbound/memory/%s.go`](../../internal/adapters/outbound/memory/%s.go) |\n", f.Feature.Name, f.Feature.Name)
	}
	if f.Adapters.Postgres {
		fmt.Fprintf(&b, "| postgres | [`internal/adapters/outbound/postgres/%s.go`](../../internal/adapters/outbound/postgres/%s.go) |\n", f.Feature.Name, f.Feature.Name)
	}
	fmt.Fprintf(&b, "| wiring | [`internal/infrastructure/app/%s_gen.go`](../../internal/infrastructure/app/%s_gen.go) |\n", f.Feature.Name, f.Feature.Name)
	return b.String()
}

func invariantSummary(f FeatureSpec) string {
	var parts []string
	for _, field := range f.Fields {
		switch {
		case field.Name == "created_at":
			parts = append(parts, "`created_at` vem do Clock")
		case field.Required && field.Type == "string":
			parts = append(parts, "`"+field.Name+"` obrigatório")
		case field.MaxLen != nil:
			parts = append(parts, fmt.Sprintf("`%s` ≤ %d", field.Name, *field.MaxLen))
		}
	}
	if len(parts) == 0 {
		return "—"
	}
	return strings.Join(parts, "; ")
}

// loadMigrations maps feature name -> migration file using the state sidecars.
func loadMigrations(root string) (map[string]string, error) {
	out := map[string]string{}
	files, err := filepath.Glob(filepath.Join(root, ".scaffold", "features", "*.state.json"))
	if err != nil {
		return nil, err
	}
	for _, file := range files {
		raw, err := os.ReadFile(file)
		if err != nil {
			return nil, err
		}
		var state struct {
			Migration string `json:"migration"`
		}
		if err := json.Unmarshal(raw, &state); err != nil {
			continue
		}
		name := strings.TrimSuffix(filepath.Base(file), ".state.json")
		if state.Migration != "" {
			out[name] = state.Migration
		}
	}
	return out, nil
}

// sortedKeys is used by tests and diagnostics.
func sortedKeys(m map[string]string) []string {
	keys := make([]string, 0, len(m))
	for key := range m {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	return keys
}
