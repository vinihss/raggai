const (
	generatedHeader = "<!-- Code generated from .scaffold/*.json by new-go-service.sh and new-feature.sh; DO NOT EDIT. -->\n"
	// generatedMarker identifies docs this tool may overwrite. legacyMarker keeps
	// projects scaffolded by older versions regenerable.
	generatedMarker = "Code generated from .scaffold/"
	legacyMarker    = "Code generated by new-go-service.sh"
)

type renderer struct {
	service    ServiceInfo
	features   []FeatureSpec
	migrations map[string]string
	// curated marks docs that exist or will be seeded; the hub only links to
	// those, so the nav never points at a missing file (DOC4).
	curated map[string]bool
}

func (r renderer) hub() string {
	var b strings.Builder
	b.WriteString(generatedHeader)
	fmt.Fprintf(&b, "\n# %s — documentação\n\n", r.service.Name)
	fmt.Fprintf(&b, "Serviço `%s` em Go %s (modo `%s`).\n\n", r.service.Module, r.service.GoVersion, r.service.Mode)
	b.WriteString("Este arquivo é o hub: todo documento abaixo é alcançável a partir daqui (regra DOC1).\n\n")
	b.WriteString("## Comece por aqui\n\n")
	r.link(&b, "Visão geral", "visao-geral.md", "o que o serviço faz e como rodar")
	b.WriteString("- [Estrutura de pastas](estrutura.md) — onde cada tipo de código vive.\n")
	b.WriteString("- [Domínio](dominio.md) — agregados e invariantes.\n")
	b.WriteString("- [API](api.md) — rotas, erros e contratos.\n")
	b.WriteString("- [Dados](dados.md) — tabelas, migrations e transações.\n")
	b.WriteString("- [Configuração](configuracao.md) — variáveis de ambiente e defaults.\n")
	r.link(&b, "Arquitetura", "arquitetura.md", "camadas, regras de dependência e fluxo de uma requisição")
	r.link(&b, "Operação", "operacao.md", "build, deploy, health e shutdown")
	r.link(&b, "Testes", "testes.md", "o que testar em cada camada")
	r.link(&b, "Decisões", "decisoes.md", "decisões arquiteturais e o porquê")
	b.WriteString("\n")
	b.WriteString("## Como este diretório é mantido\n\n")
	b.WriteString("| Tipo | Arquivos | Quem escreve |\n")
	b.WriteString("| --- | --- | --- |\n")
	b.WriteString("| Gerado | `README.md`, `estrutura.md`, `dominio.md`, `api.md`, `dados.md`, `configuracao.md`, `features/*.md` | `new-go-service.sh` e `new-feature.sh` (não edite) |\n")
	b.WriteString("| Curado | `visao-geral.md`, `arquitetura.md`, `operacao.md`, `testes.md`, `decisoes.md` | você (nunca é sobrescrito) |\n\n")
	b.WriteString("Regras de documentação (DOC1–DOC6) estão no guia, seção 14.4.\n")
	return b.String()
}

// link writes a curated link only when the target exists or will be seeded.
func (r renderer) link(b *strings.Builder, title, target, description string) {
	if !r.curated[target] {
		return
	}
	fmt.Fprintf(b, "- [%s](%s) — %s.\n", title, target, description)
}

