const generatedMarker = "Code generated by new-feature.sh"

// headerComment opens every generated Go file. It is also the ownership signal
// used by the writer: only files carrying it can be overwritten automatically.
func headerComment(b *strings.Builder, m *Model) {
	fmt.Fprintf(b, "// %s from .scaffold/features/%s.json; DO NOT EDIT.\n//\n", generatedMarker, m.Name)
}

// output is one file the generator intends to write.
type output struct {
	path string
	body string
	// skipIfExists protects applied migrations: they are append-only.
	skipIfExists bool
}

// featureState records what was generated for a feature so reruns are safe and
// migrations keep their original version number.
type featureState struct {
	Migration string   `json:"migration,omitempty"`
	Files     []string `json:"files"`
	SpecSHA   string   `json:"spec_sha256"`
}

func sha256Hex(data []byte) string {
	sum := sha256.Sum256(data)
	return hex.EncodeToString(sum[:])
}

func featureDir(root, name string) string {
	return filepath.Join(root, ".scaffold", "features", name)
}

func statePath(root, name string) string {
	return featureDir(root, name) + ".state.json"
}

func specPath(root, name string) string {
	return featureDir(root, name) + ".json"
}

func loadFeatureState(root, name string) (featureState, error) {
	var state featureState
	raw, err := os.ReadFile(statePath(root, name))
	if err != nil {
		if os.IsNotExist(err) {
			return state, nil
		}
		return state, err
	}
	if err := json.Unmarshal(raw, &state); err != nil {
		return state, fmt.Errorf("estado inválido para %s: %w", name, err)
	}
	return state, nil
}

func saveFeatureState(root, name string, state featureState) error {
	if err := os.MkdirAll(filepath.Dir(statePath(root, name)), 0o755); err != nil {
		return err
	}
	sort.Strings(state.Files)
	raw, err := json.MarshalIndent(state, "", "  ")
	if err != nil {
		return err
	}
	return os.WriteFile(statePath(root, name), append(raw, '\n'), 0o644)
}

// saveSpecCopy keeps the descriptor next to the generated code so a later run
// can regenerate every feature without the original file.
func saveSpecCopy(root, name string, raw []byte) error {
	if err := os.MkdirAll(filepath.Dir(specPath(root, name)), 0o755); err != nil {
		return err
	}
	return os.WriteFile(specPath(root, name), raw, 0o644)
}

var migrationPattern = regexp.MustCompile(`^(\d{4})_.*\.sql$`)

// nextMigrationVersion returns the next free forward-only version.
func nextMigrationVersion(dir string) (int, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		if os.IsNotExist(err) {
			return 1, nil
		}
		return 0, err
	}
	max := 0
	for _, entry := range entries {
		match := migrationPattern.FindStringSubmatch(entry.Name())
		if match == nil {
			continue
		}
		version, err := strconv.Atoi(match[1])
		if err != nil {
			continue
		}
		if version > max {
			max = version
		}
	}
	return max + 1, nil
}

func migrationName(version int, table string) string {
	return fmt.Sprintf("%04d_create_%s.sql", version, table)
}

// isGenerated reports whether an existing file can be regenerated.
func isGenerated(raw []byte) bool {
	return bytes.Contains(raw, []byte(generatedMarker))
}

// formatGo validates the emitted code and normalizes it. A generator bug fails
// here, before the file reaches the user's tree.
func formatGo(path, body string) (string, error) {
	formatted, err := format.Source([]byte(body))
	if err != nil {
		return "", fmt.Errorf("código gerado inválido em %s: %w\n%s", path, err, snippet(body))
	}
	return string(formatted), nil
}

func snippet(body string) string {
	lines := strings.Split(body, "\n")
	const max = 80
	if len(lines) > max {
		lines = append(lines[:max], "...")
	}
	return strings.Join(lines, "\n")
}

// writeOutputs writes the plan, refusing to clobber files the generator does
// not own. It returns the paths that were actually written.
func writeOutputs(root string, outs []output, force bool, dryRun bool, w io.Writer) ([]string, error) {
	var written []string

	for _, item := range outs {
		target := filepath.Join(root, item.path)

		existing, readErr := os.ReadFile(target)
		exists := readErr == nil

		switch {
		case item.skipIfExists && exists:
			fmt.Fprintf(w, "  skip    %s (migration já aplicada)\n", item.path)
			written = append(written, item.path)
			continue
		case exists && string(existing) == item.body:
			fmt.Fprintf(w, "  same    %s\n", item.path)
			written = append(written, item.path)
			continue
		case exists && !isGenerated(existing) && !force:
			return written, fmt.Errorf("%s já existe e não foi gerado por new-feature.sh (use --force para sobrescrever)", item.path)
		}

		if dryRun {
			fmt.Fprintf(w, "  create  %s\n", item.path)
			written = append(written, item.path)
			continue
		}

		if err := os.MkdirAll(filepath.Dir(target), 0o755); err != nil {
			return written, err
		}
		if err := os.WriteFile(target, []byte(item.body), 0o644); err != nil {
			return written, err
		}
		fmt.Fprintf(w, "  write   %s\n", item.path)
		written = append(written, item.path)
	}
	return written, nil
}

// emitFeatureRegistry regenerates infrastructure/app/features_gen.go from every
// known feature plus the scaffold example. Callers pass models sorted by name.
func emitFeatureRegistry(models []*Model, ping bool) string {
	var b strings.Builder

	b.WriteString("// Code generated by new-feature.sh from .scaffold/features/*.json; DO NOT EDIT.\n")
	b.WriteString("//\n// Regra do guia (F4): o wiring é explícito e vive no composition root.\n")
	b.WriteString("package app\n\nimport \"net/http\"\n\n")

	if len(models) == 0 && !ping {
		b.WriteString("// registerFeatures is generated; adicione features com new-feature.sh.\n")
		b.WriteString("func registerFeatures(_ *http.ServeMux, _ Dependencies) error {\n\treturn nil\n}\n")
		return b.String()
	}

	b.WriteString("// registerFeatures is generated. Edit `.scaffold/features/*.json` and rerun\n")
	b.WriteString("// new-feature.sh instead of editing this file.\n")
	b.WriteString("func registerFeatures(api *http.ServeMux, deps Dependencies) error {\n")
	if ping {
		b.WriteString("\tif err := registerPing(api, deps); err != nil {\n\t\treturn err\n\t}\n")
	}
	for _, m := range models {
		fmt.Fprintf(&b, "\tif err := register%s(api, deps); err != nil {\n\t\treturn err\n\t}\n", m.Type)
	}
	b.WriteString("\treturn nil\n}\n")
	return b.String()
}

// emitFeatureWiring writes the per-feature composition file.
func emitFeatureWiring(m *Model) string {
	usePostgres := m.HasPostgres && m.Service.Mode == "full"

	var b strings.Builder
	headerComment(&b, m)
	b.WriteString("package app\n\n")
	b.WriteString("import (\n\t\"net/http\"\n\n")
	fmt.Fprintf(&b, "\thttpadapter \"%s/internal/adapters/inbound/http\"\n", m.Service.Module)
	if usePostgres {
		fmt.Fprintf(&b, "\t\"%s/internal/adapters/outbound/postgres\"\n", m.Service.Module)
	} else {
		fmt.Fprintf(&b, "\t\"%s/internal/adapters/outbound/memory\"\n", m.Service.Module)
	}
	fmt.Fprintf(&b, "\tapp%s \"%s/internal/application/%s\"\n)\n\n", m.Name, m.Service.Module, m.Name)

	fmt.Fprintf(&b, "// register%s wires the %s feature into the API mux.\n", m.Type, m.Name)
	fmt.Fprintf(&b, "func register%s(api *http.ServeMux, deps Dependencies) error {\n", m.Type)
	if usePostgres {
		fmt.Fprintf(&b, "\trepo := postgres.New%sRepository(deps.DB)\n", m.Type)
	} else {
		fmt.Fprintf(&b, "\trepo := memory.New%sRepository()\n", m.Type)
	}
	fmt.Fprintf(&b, "\tservice := app%s.NewService(repo, deps.Clock, deps.IDs)\n", m.Name)
	fmt.Fprintf(&b, "\thttpadapter.Register%s(api, service)\n", m.Type)
	b.WriteString("\treturn nil\n}\n")
	return b.String()
}
